# ── Helper: structured error ────────────────────────────────────────────────────
def _err(code, error, details="", stage="unknown", http=422):
    """
    All API errors return a consistent structure.
    Never returns a blank 422 response.
    """
    return jsonify(
        success = False,
        code    = code,
        error   = error,
        details = details,
        stage   = stage,
    ), http

# ── Helper: extract stage from Lua stderr (F8) ─────────────────────────────────
def _extract_stage(stderr):
    """
    F8: Expanded to recognise common Lua runtime error patterns.
    Previously only matched [X999] error codes and always returned 'unknown'.
    Now maps concrete stderr patterns to actionable stage names.
    """
    if not stderr:
        return "unknown"

    s = stderr.lower()

    # Internal error codes e.g. [P001], [V002], [B003]
    m = re.search(r'\[([A-Z]\d+)\]', stderr)
    if m:
        prefix_map = {'P':'parse','V':'validation','B':'bytecode','R':'runtime','C':'compiler','M':'compat'}
        return prefix_map.get(m.group(1)[0], 'engine')

    # Lua module-not-found (e.g. missing compat.lua)
    if "module" in s and ("not found" in s or "no field" in s):
        return "module_load"

    # Lua lexer errors (spec.lua 10_ etc.)
    if "malformed number" in s:
        return "lua_lexer"

    # Lua syntax errors in user source
    if "syntax error" in s or "unexpected symbol" in s:
        return "parse"

    # Stack overflow / timeout
    if "stack overflow" in s:
        return "runtime"
    if "attempt to" in s:
        return "runtime"

    return "engine"

# ── Helper: extract human error from Lua stderr ───────────────────────────────
def _clean_error(stderr):
    """Extract the most relevant error line from Lua stderr."""
    if not stderr:
        return "Unknown engine error."
    lines = [l.strip() for l in stderr.strip().splitlines() if l.strip()]
    if not lines:
        return "Unknown engine error."
    # Prefer lines with ': ' (Lua error format)
    for line in lines:
        if ': ' in line:
            return line
    return lines[0]

