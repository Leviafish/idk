@app.route("/api/obfuscate", methods=["POST"])
def obfuscate():
    # Engine check
    if not _LUA_PATH:
        return _err("NO_LUA_ENGINE",
            "Lua 5.4 runtime is not available on this server.",
            "Install Lua 5.4 or deploy with the provided Dockerfile.",
            stage="engine_check", http=503)

    # Parse request body
    data = request.get_json(force=True, silent=True)
    if not isinstance(data, dict):
        return _err("INVALID_REQUEST", "Request body must be JSON.", http=400)

    source = (data.get("source") or "").strip()
    if not source:
        return _err("EMPTY_SOURCE", "No source code provided.", stage="input", http=400)
    if len(source.encode("utf-8")) > 800_000:
        return _err("SOURCE_TOO_LARGE", "Source exceeds 800 KB limit.", stage="input", http=413)

    opts   = data.get("options", {}) if isinstance(data.get("options"), dict) else {}
    target = str(opts.get("target", "lua54"))
    seed   = opts.get("seed")
    maxIC  = int(opts.get("maxInstructions", 10000000))
    protect= opts.get("protectNames", [])
    if not isinstance(protect, list):
        protect = []

    # Target validation
    valid_targets    = {"lua54", "lua53", "luajit", "luau"}
    unsupported      = {"lua51", "lua52"}
    if target in unsupported:
        return _err("UNSUPPORTED_TARGET",
            f"Target '{target}' is not supported.",
            f"Supported targets: {', '.join(sorted(valid_targets))}",
            stage="compat", http=400)
    if target not in valid_targets:
        return _err("UNKNOWN_TARGET", f"Unknown target '{target}'.",
            stage="compat", http=400)

    # File setup
    uid      = uuid.uuid4().hex
    src_path = os.path.join(OUTPUT_DIR, f"{uid}_in.lua")
    out_path = os.path.join(OUTPUT_DIR, f"{uid}_out.lua")
    build_seed = int(seed) if seed is not None else (int(time.time() * 1000) ^ random.randint(0, 0xFFFF))

    try:
        with open(src_path, "w", encoding="utf-8") as f:
            f.write(source)

        args = [_LUA_PATH, _CLI_PATH, src_path,
                "-o", out_path,
                "--target", target,
                "--max-instr", str(maxIC)]

        if seed is not None:
            args += ["--seed", str(int(seed))]
        for name in protect:
            n = str(name).strip()
            if n:
                args += ["--protect", n]

        t0     = time.time()
        result = subprocess.run(args, capture_output=True, text=True, timeout=30)
        elapsed = round(time.time() - t0, 3)

        if result.returncode != 0:
            stderr = result.stderr or result.stdout or ""
            stage  = _extract_stage(stderr)
            msg    = _clean_error(stderr)
            return _err("ENGINE_ERROR", msg, stderr.strip(), stage=stage, http=422)

        if not os.path.exists(out_path):
            return _err("NO_OUTPUT", "Engine produced no output file.", stage="output", http=500)

        with open(out_path, "r", encoding="utf-8") as f:
            raw = f.read()

        # Replace Levititas engine header with randomized brand token
        brand_header = generate_header_comment(build_seed)
        obfuscated = re.sub(
            r'^-- Levititas v[\d.]+ \|[^\n]*\n',
            brand_header + "\n",
            raw, count=1, flags=re.MULTILINE
        )
        if obfuscated == raw:
            obfuscated = brand_header + "\n" + raw

        return jsonify(
            success = True,
            result  = obfuscated,
            elapsed = elapsed,
            seed    = build_seed,
            brand   = brand_header,
            stats   = _stats(source, obfuscated),
            engine  = "lua-full",
            target  = target,
        )

    except subprocess.TimeoutExpired:
        return _err("TIMEOUT", "Obfuscation timed out after 30s.", stage="runtime", http=408)
    except Exception as e:
        return _err("SERVER_ERROR", str(e), stage="server", http=500)
    finally:
        for p in (src_path, out_path):
            try: os.remove(p)
            except: pass

def _stats(original, obfuscated):
    return {
        "originalBytes":   len(original.encode("utf-8")),
        "obfuscatedBytes": len(obfuscated.encode("utf-8")),
        "originalLines":   original.count("\n") + 1,
        "obfuscatedLines": obfuscated.count("\n") + 1,
        "ratio":           round(len(obfuscated) / max(len(original), 1), 2),
    }

