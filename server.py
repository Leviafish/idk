# ── Cleanup ────────────────────────────────────────────────────────────────────
def _cleanup():
    while True:
        time.sleep(600)
        now = time.time()
        for f in os.listdir(OUTPUT_DIR):
            fp = os.path.join(OUTPUT_DIR, f)
            try:
                if now - os.path.getmtime(fp) > 600:
                    os.remove(fp)
            except Exception:
                pass
threading.Thread(target=_cleanup, daemon=True).start()

# ── Lua detection (F7: prefer versioned binary) ────────────────────────────────
def _lua():
    """
    F7: Search order changed — versioned binaries tried first.
    This prevents accidentally picking up Lua 5.3 or 5.1 when `lua` is symlinked
    to an older version, which would cause spec.lua to crash on load.
    """
    for name in ("lua5.4", "lua54", "lua-5.4", "lua"):
        path = shutil.which(name)
        if path:
            # Verify it's actually 5.4+ (belt-and-suspenders)
            try:
                r = subprocess.run([path, "-v"], capture_output=True, text=True, timeout=3)
                ver_str = (r.stdout or r.stderr or "").strip()
                if "Lua 5.4" in ver_str or "Lua 5.5" in ver_str or "LuaJIT" in ver_str:
                    return path
                if name != "lua":
                    # Named specifically — trust it even if version string is odd
                    return path
            except Exception:
                continue
    # Last resort: unversioned `lua` whatever it is
    return shutil.which("lua")

def _lua_version(lua_path):
    if not lua_path: return None
    try:
        r = subprocess.run([lua_path, "-v"], capture_output=True, text=True, timeout=5)
        return (r.stdout or r.stderr or "").strip()
    except Exception:
        return None

