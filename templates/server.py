from flask import Flask, request, jsonify, render_template, send_from_directory
import subprocess, os, uuid, time, json, threading, shutil, random

# Import brand generator
import sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'static'))
try:
    from brand import generate_header_comment, generate_brand
except ImportError:
    def generate_brand(seed=None): return "Lev1titas"
    def generate_header_comment(seed=None):
        return f"-- This file was generated by {generate_brand(seed)} | {time.strftime('%Y-%m-%d')}"

app = Flask(__name__, template_folder="templates", static_folder="static")
app.config["MAX_CONTENT_LENGTH"] = 4 * 1024 * 1024

OUTPUT_DIR = os.path.join(os.path.dirname(__file__), "output")
os.makedirs(OUTPUT_DIR, exist_ok=True)

# ── Cleanup ────────────────────────────────────────────────────
def _cleanup():
    while True:
        time.sleep(600)
        now = time.time()
        for f in os.listdir(OUTPUT_DIR):
            fp = os.path.join(OUTPUT_DIR, f)
            try:
                if now - os.path.getmtime(fp) > 600:
                    os.remove(fp)
            except Exception:
                pass
threading.Thread(target=_cleanup, daemon=True).start()

# ── Lua detection ──────────────────────────────────────────────
def _lua():
    for name in ("lua", "lua5.4", "lua54"):
        path = shutil.which(name)
        if path:
            return path
    return None

def _lua_version():
    lua = _lua()
    if not lua:
        return None
    try:
        r = subprocess.run([lua, "-v"], capture_output=True, text=True, timeout=5)
        return (r.stdout or r.stderr or "").strip()
    except Exception:
        return None

_LUA_PATH    = _lua()
_LUA_VERSION = _lua_version()
_CLI_PATH    = os.path.join(os.path.dirname(__file__), "levititas.lua")
_START_TIME  = time.time()

print(f"[Levititas v3.3] Starting")
if _LUA_PATH:
    print(f"[Levititas v3.3] ✓ Lua: {_LUA_VERSION}")
else:
    print("[Levititas v3.3] ✗ Lua not found — install Lua 5.4")

