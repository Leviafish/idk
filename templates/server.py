@app.route("/api/brand")
def brand():
    """Return a fresh randomized brand name."""
    seed = request.args.get("seed")
    build_seed = int(seed) if seed else None
    return jsonify(
        brand  = generate_brand(build_seed),
        header = generate_header_comment(build_seed),
    )

@app.route("/api/obfuscate", methods=["POST"])
def obfuscate():
    if not _LUA_PATH:
        return jsonify(
            ok    = False,
            error = (
                "Lua 5.4 is not installed on this server. "
                "Deploy using the provided Dockerfile which pre-installs Lua 5.4, "
                "or install Lua locally: https://www.lua.org/download.html"
            ),
            stage = "engine_check",
            code  = "NO_LUA_ENGINE",
        ), 503

    data   = request.get_json(force=True, silent=True) or {}
    source = data.get("source", "").strip()
    if not source:
        return jsonify(ok=False, error="No source code provided.", stage="input"), 400
    if len(source) > 800_000:
        return jsonify(ok=False, error="Source too large (max 800 KB).", stage="input"), 413

    opts   = data.get("options", {})
    target = opts.get("target", "lua54")
    seed   = opts.get("seed")
    maxIC  = opts.get("maxInstructions", 10_000_000)
    protect= opts.get("protectNames", [])

    valid_targets    = {"lua54","lua53","luajit","luau"}
    unsupported      = {"lua51","lua52"}
    if target in unsupported:
        return jsonify(ok=False, error=f"Target '{target}' is not supported. Supported: {', '.join(sorted(valid_targets))}", stage="compat", code="UNSUPPORTED_TARGET"), 400
    if target not in valid_targets:
        return jsonify(ok=False, error=f"Unknown target '{target}'.", stage="compat", code="UNKNOWN_TARGET"), 400

    uid      = uuid.uuid4().hex
    src_path = os.path.join(OUTPUT_DIR, f"{uid}_in.lua")
    out_path = os.path.join(OUTPUT_DIR, f"{uid}_out.lua")

    # Generate build seed for brand name
    build_seed = seed if seed else int(time.time() * 1000) ^ random.randint(0, 0xFFFF)
    brand_header = generate_header_comment(build_seed)

    try:
        with open(src_path, "w", encoding="utf-8") as f:
            f.write(source)

        args = [_LUA_PATH, _CLI_PATH, src_path, "-o", out_path,
                "--target", target, "--max-instr", str(int(maxIC))]

        if seed is not None:
            args += ["--seed", str(int(seed))]
        for name in protect:
            if name and name.strip():
                args += ["--protect", name.strip()]

        t0     = time.time()
        result = subprocess.run(args, capture_output=True, text=True, timeout=30)
        elapsed= round(time.time() - t0, 3)

        if result.returncode != 0:
            stderr = result.stderr or result.stdout or "Unknown error"
            return jsonify(ok=False, error=stderr.strip(), stage=_extract_stage(stderr), elapsed=elapsed), 422

        if not os.path.exists(out_path):
            return jsonify(ok=False, error="Obfuscator produced no output.", stage="output"), 500

        with open(out_path, "r", encoding="utf-8") as f:
            raw = f.read()

        # Replace any plain Levititas header with randomized brand header
        import re
        obfuscated = re.sub(
            r'^-- Levititas v[\d.]+ \|[^\n]*\n',
            brand_header + "\n",
            raw, count=1, flags=re.MULTILINE
        )
        if obfuscated == raw:
            # No header found — prepend one
            obfuscated = brand_header + "\n" + raw

        return jsonify(
            ok       = True,
            result   = obfuscated,
            elapsed  = elapsed,
            seed     = build_seed,
            brand    = brand_header,
            stats    = _stats(source, obfuscated),
            engine   = "lua-full",
        )

    except subprocess.TimeoutExpired:
        return jsonify(ok=False, error="Obfuscation timed out (30s).", stage="runtime", code="TIMEOUT"), 408
    except Exception as e:
        return jsonify(ok=False, error=str(e), stage="server"), 500
    finally:
        for p in (src_path, out_path):
            try: os.remove(p)
            except: pass

def _stats(original, obfuscated):
    return {
        "originalBytes":   len(original.encode()),
        "obfuscatedBytes": len(obfuscated.encode()),
        "originalLines":   original.count("\n") + 1,
        "obfuscatedLines": obfuscated.count("\n") + 1,
        "ratio":           round(len(obfuscated) / max(len(original), 1), 2),
    }

def _extract_stage(stderr):
    import re
    m = re.search(r'\[([A-Z]\d+)\]', stderr)
    if m:
        stages = {'P':'parse','V':'validation','B':'bytecode','R':'runtime','C':'compiler'}
        return stages.get(m.group(1)[0], 'unknown')
    return 'unknown'

