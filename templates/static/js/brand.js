'use strict';
/**
 * Levititas v3.3 — Client-side Brand Generator
 * static/js/brand.js
 *
 * Generates randomized brand name variants for output headers.
 * Seed stored as char codes - never as plaintext string.
 * Mirrors server-side brand.py logic.
 */

const BrandGen = (() => {

  // Seed stored as char code array — never plaintext
  const _SEED_CODES = [76,101,118,105,116,105,116,97,115];
  const _decode = () => String.fromCharCode(..._SEED_CODES);

  // Substitution tables
  const _SUBS = [
    { e:'3', i:'1', a:'4', o:'0', t:'7', s:'5' },       // leet
    { e:'€', i:'!', a:'@', o:'0', t:'+', s:'$' },       // symbols
    { e:'E', i:'I', a:'A', o:'O', t:'T', s:'S' },       // caps
    { e:'ε', i:'ι', a:'α', o:'ο', t:'τ', s:'ς' },       // greek
    { e:'e', i:'i', a:'a', o:'o', t:'†', s:'ƨ' },       // special
  ];

  // Drop patterns (indices to remove)
  const _DROPS = [
    [2,5], [3], [4,6], [1], [5,7], [0,4], [2,6],
  ];

  // Simple seeded PRNG (xorshift32)
  function _rng(seed) {
    let s = (seed >>> 0) || 1;
    return () => {
      s ^= s << 13; s ^= s >>> 17; s ^= s << 5;
      return (s >>> 0) / 0xFFFFFFFF;
    };
  }

  function _choice(arr, r) { return arr[Math.floor(r() * arr.length)]; }

  function generate(buildSeed) {
    const seed = buildSeed !== undefined
      ? buildSeed
      : Math.floor(Date.now() / 1000) ^ Math.floor(Math.random() * 0xFFFF);

    const r    = _rng(seed);
    let brand  = _decode();

    // 1. Substitution
    const sub = _choice(_SUBS, r);
    let result = '';
    for (const ch of brand) {
      const lo = ch.toLowerCase();
      if (sub[lo] && r() > 0.35) {
        const rep = sub[lo];
        result += (ch !== lo && /[a-zA-Z]/.test(rep))
          ? rep.toUpperCase() : rep;
      } else {
        result += ch;
      }
    }

    // 2. Drop pattern
    const drop = _choice(_DROPS, r);
    const chars = [...result];
    [...drop].sort((a,b) => b-a).forEach(idx => {
      if (idx < chars.length) chars.splice(idx, 1);
    });
    result = chars.join('');

    // 3. Case mutation
    let final = '';
    for (const ch of result) {
      if (/[a-zA-Z]/.test(ch) && r() > 0.6) {
        final += ch === ch.toUpperCase() ? ch.toLowerCase() : ch.toUpperCase();
      } else {
        final += ch;
      }
    }

    if (final.length < 4) final = result.slice(0, 4);
    return final;
  }

  function headerComment(buildSeed) {
    const brand = generate(buildSeed);
    const date  = new Date().toISOString().slice(0, 10);
    return `-- This file was generated by ${brand} | ${date}`;
  }

  function variants(n = 6) {
    const base = Math.floor(Date.now() / 1000);
    return Array.from({length: n}, (_, i) => generate(base + i * 7919));
  }

  return { generate, headerComment, variants };

})();
